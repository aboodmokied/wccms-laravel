-- ============================================================================
-- 01_hos_stub.sql: a minimal stand-in for the hospital schema HOS (run as SYSTEM).
--
-- Only the tables WCCMS reads, with the columns the application uses, HOS_NO, and composite primary keys
-- (code, HOS_NO) as in the real hospital database. Two hospitals (HOS_NO 1 and 2) share the same codes on
-- purpose, so the tests can tell "exists in this hospital" from "exists somewhere".
--
-- It first drops the users WCCMS and HOS if they exist: every run starts from an empty database.
-- ============================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF
SET SERVEROUTPUT ON
SET FEEDBACK OFF

BEGIN
    FOR u IN (
        SELECT username FROM dba_users WHERE username IN ('WCCMS', 'HOS')
        ORDER BY CASE username WHEN 'WCCMS' THEN 1 ELSE 2 END
    ) LOOP
        EXECUTE IMMEDIATE 'DROP USER ' || u.username || ' CASCADE';
        DBMS_OUTPUT.PUT_LINE('Dropped user ' || u.username);
    END LOOP;
END;
/

CREATE USER HOS IDENTIFIED BY "Hos_Stub_1" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO HOS;

-- The real HOS schema owns a type with this name (PL/JSON). WCCMS must not depend on it or clash with it.
