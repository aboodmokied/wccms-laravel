-- Target: Oracle 11g (11.2) or later. Every identifier is 30 characters or fewer.
-- Creates everything WCCMS needs IN THE ACCOUNT YOU ARE CONNECTED WITH. The hospital tables (schema HOS) are
-- only read, never created or changed.
-- ============================================================================
--
-- لا شيء يُستبدل في هذا الملف: لا كلمة مرور ولا tablespace، ولا يُنشأ مستخدم جديد.
-- كل الجداول والدوال والـ procedures تُنشأ في الحساب المتصل الآن، في الـ tablespace الافتراضي له.
-- النظام يتصل بالحساب نفسه: اكتب اسمه وكلمة مروره في DB_USERNAME و DB_PASSWORD في ملف .env.
--
-- ما يحتاجه الحساب المتصل (القسم 1 يفحصه أولاً، ويتوقف برسالة تقول ما الناقص قبل أن يُنشئ أي شيء):
--   - صلاحيات CREATE TABLE و CREATE PROCEDURE و CREATE TYPE.
--   - مساحة تخزين (quota) في الـ tablespace الافتراضي له، أو UNLIMITED TABLESPACE.
--   - قراءة جداول HOS الثمانية: الحساب هو HOS نفسه، أو له GRANT SELECT عليها، أو DBA.
--   - ألا يكون فيه مسبقاً أي كائن بالأسماء التي ينشئها هذا الملف (WC_*_TB و WC_CODE_LIST و FN_WC_* و SP_WC_*).
--   - ألا يكون SYS.
--
-- طريقة التشغيل
--   SQL Developer: الصق الملف كاملاً في Worksheet واحدة، ثم Run Script (F5)، لا Run Statement (Ctrl+Enter).
--                  انسخه من محرر يعرض العربي سليماً (VS Code أو Notepad++)؛ وإن فتحت الملف في SQL Developer
--                  بدل اللصق فاجعل قبلها Tools > Preferences > Environment > Encoding = UTF-8.
--   SQL*Plus:      set NLS_LANG=AMERICAN_AMERICA.AL32UTF8   (Linux: export NLS_LANG=...)
--                  sqlplus <user>/<password>@//<server>:1521/<service>
--                  SQL> @wccms_oracle_install.sql
--   الملف يتوقف عند أول خطأ.
--   لإعادة التشغيل من البداية بعد خطأ: نفّذ wccms_oracle_uninstall.sql بالحساب نفسه (يحذف كائنات WCCMS بأسمائها
--   فقط ولا يلمس غيرها)، ثم هذا الملف من جديد.
--   الملف ينتهي بخطأ ORA-20000 إذا بقي أي كائن من كائنات WCCMS بحالة INVALID.
--
-- الـ procedures تعمل بصلاحيات من يستدعيها (AUTHID CURRENT_USER): تكفي قراءة HOS عبر role (مثل DBA)، بشرط أن
