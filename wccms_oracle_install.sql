-- FN_WC_NOW: الوقت الحالي بتوقيت UTC بغض النظر عن توقيت الخادم أو الجلسة (بدل SYSDATE).
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION FN_WC_NOW RETURN DATE
IS
BEGIN
