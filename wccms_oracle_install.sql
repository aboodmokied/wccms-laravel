-- ----------------------------------------------------------------------------
-- FN_WC_UUID: 32 حرفاً سداسياً من SYS_GUID بشكل UUID بحروف صغيرة، مثل 3f2a9c1e-....
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION FN_WC_UUID RETURN VARCHAR2
IS
BEGIN
    RETURN LOWER(REGEXP_REPLACE(RAWTOHEX(SYS_GUID()), '^(.{8})(.{4})(.{4})(.{4})(.{12})$', '\1-\2-\3-\4-\5'));
END FN_WC_UUID;
/
SHOW ERRORS

