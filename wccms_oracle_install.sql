-- ============================================================================
-- 1) فحص الحساب المتصل: لا يُنشئ شيئاً، ويتوقف برسالة واضحة (ORA-20000) إن نقص شيء.
-- ============================================================================
DECLARE
    v_hos   SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST(
                'MR_PATIENT_TB', 'EMPLOYEE_TB', 'ADMISSION_PATIENT_TB', 'INPATIENT_ADM_TB',
                'C_LOCATION_TB', 'C_SEX_TB', 'C_JOB_TB', 'C_HOSPITAL_TB');
    -- كل كائن ينشئه هذا الملف بالاسم (ونفس القائمة في wccms_oracle_uninstall.sql).
    v_ours  SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST(
                'WC_USERS_TB', 'WC_DEPARTMENT_TB', 'WC_PMH_TB', 'WC_DIAGNOSIS_TB', 'WC_WOUND_TYPE_TB',
                'WC_DRESSING_TB', 'WC_MEDICATION_TB', 'WC_PROCEDURE_TB', 'WC_REQUEST_REG_TB', 'WC_REGISTRATION_TB',
                'WC_REG_DIAGNOSIS_TB', 'WC_SCHEDULED_REVIEW_TB', 'WC_DAILY_REVIEW_TB', 'WC_REVIEW_DETAIL_TB',
                'WC_ASSESSMENT_CHOICE_TB', 'WC_REGISTRATION_PMH_TB', 'WC_WOUND_ASSESSMENT_TB',
                'WC_ASSESSMENT_FINDING_TB', 'WC_WOUND_PHOTO_TB', 'WC_REPORT_EXPORT_TB',
                'WC_CODE_LIST', 'FN_WC_UUID', 'FN_WC_NOW', 'FN_WC_TO_DATE', 'FN_WC_TO_CODE', 'FN_WC_XML_TEXT',
                'FN_WC_XML_FLAG', 'FN_WC_XML_NUMBER', 'FN_WC_XML_ITEM_COUNT', 'FN_WC_XML_ITEM', 'FN_WC_XML_CODES',
                'FN_WC_EMPLOYEE_EXISTS', 'SP_WC_INSERT_ASSESSMENT', 'SP_WC_ACCEPT_REGISTRATION',
                'SP_WC_COMPLETE_REVIEW', 'SP_WC_ADD_WOUND');
    v_privs SYS.ODCIVARCHAR2LIST := SYS.ODCIVARCHAR2LIST('TABLE', 'PROCEDURE', 'TYPE');
    v_count NUMBER;
    v_list  VARCHAR2(4000);
    v_ts    VARCHAR2(30);
BEGIN
    IF USER = 'SYS' THEN
        RAISE_APPLICATION_ERROR(-20000, 'WCCMS install: do not run this file as SYS. Connect with the account '
            || 'the system will use (DB_USERNAME in .env) and run it again.');
    END IF;

    -- أ) صلاحيات الإنشاء
    FOR i IN 1 .. v_privs.COUNT LOOP
        SELECT COUNT(*) INTO v_count FROM session_privs
         WHERE privilege IN ('CREATE ' || v_privs(i), 'CREATE ANY ' || v_privs(i));
        IF v_count = 0 THEN
            v_list := v_list || ' CREATE ' || v_privs(i) || ',';
        END IF;
    END LOOP;
    IF v_list IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20000, 'WCCMS install: account ' || USER || ' is missing:' || RTRIM(v_list, ',')
            || '. Ask the DBA: GRANT CREATE TABLE, CREATE PROCEDURE, CREATE TYPE TO ' || USER || ';');
    END IF;

    -- ب) مساحة التخزين
    SELECT default_tablespace INTO v_ts FROM user_users;
    SELECT COUNT(*) INTO v_count FROM session_privs WHERE privilege = 'UNLIMITED TABLESPACE';
    IF v_count = 0 THEN
        SELECT COUNT(*) INTO v_count FROM user_ts_quotas
         WHERE tablespace_name = v_ts AND (max_bytes = -1 OR max_bytes > bytes);
    END IF;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20000, 'WCCMS install: account ' || USER || ' has no space (quota) on its default '
            || 'tablespace ' || v_ts || '. Ask the DBA: ALTER USER ' || USER || ' QUOTA UNLIMITED ON ' || v_ts || ';');
    END IF;

    -- ج) قراءة جداول HOS الثمانية
    v_list := NULL;
    FOR i IN 1 .. v_hos.COUNT LOOP
        BEGIN
            EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM HOS.' || v_hos(i) || ' WHERE ROWNUM = 1' INTO v_count;
        EXCEPTION
            WHEN OTHERS THEN
                v_list := v_list || ' HOS.' || v_hos(i) || ',';
        END;
    END LOOP;
    IF v_list IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20000, 'WCCMS install: account ' || USER || ' cannot read:' || RTRIM(v_list, ',')
            || '. Ask the owner of HOS: GRANT SELECT ON HOS.<table> TO ' || USER || '; for each table above.');
    END IF;

    -- د) لا كائن موجود مسبقاً بأحد أسمائنا (وإلا يستبدل CREATE OR REPLACE كائناً ليس لنا)
    SELECT LISTAGG(object_name || ' (' || object_type || ')', ', ') WITHIN GROUP (ORDER BY object_name)
      INTO v_list
      FROM user_objects
     WHERE object_name IN (SELECT COLUMN_VALUE FROM TABLE(v_ours));
    IF v_list IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20000, 'WCCMS install: these objects already exist in ' || USER || ': ' || v_list
            || '. If they come from an earlier WCCMS run, run wccms_oracle_uninstall.sql first. If not, they belong '
            || 'to another system: do not install WCCMS in this account.');
    END IF;

    -- كل ما يلي يُنشأ في هذا الحساب، حتى لو كانت الجلسة قد غيّرت CURRENT_SCHEMA.
    EXECUTE IMMEDIATE 'ALTER SESSION SET CURRENT_SCHEMA = "' || USER || '"';
    DBMS_OUTPUT.PUT_LINE('WCCMS install: checks passed. Installing into schema ' || USER
        || ' (default tablespace ' || v_ts || ').');
END;
