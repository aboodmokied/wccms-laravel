-- ----------------------------------------------------------------------------
-- 2.1 WC_USERS_TB: "أُدخل بواسطة" (جدول WCCMS، وليس HOS.PER_USERS_TB)
-- لا تسجيل دخول في WCCMS: فيه صف واحد، حساب النظام WCCMS_SYSTEM (PER_USER_CODE = 00000000-0000-0000-0000-000000000001)،
-- ينشئه التطبيق تلقائياً، وتشير إليه أعمدة ENTRY_USER في كل الجداول. من قام بالعمل السريري يُحفظ منفصلاً: الممرض
-- والطبيب وفريق الجروح المختارون من قائمة الموظفين في كل نموذج.
-- PER_USER_EMP_CD + PER_USER_HOS_NO: ربط اختياري بموظف في HOS.EMPLOYEE_TB (الفهرس UX_WC_USERS_EMP في القسم 4).
